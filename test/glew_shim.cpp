extern "C" { void* __glewActiveTexture = nullptr; }
extern "C" { void* __glewAttachShader = nullptr; }
extern "C" { void* __glewBindBuffer = nullptr; }
extern "C" { void* __glewBindFramebuffer = nullptr; }
extern "C" { void* __glewBindRenderbuffer = nullptr; }
extern "C" { void* __glewBindVertexArray = nullptr; }
