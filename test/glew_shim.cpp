extern "C" { void* __glewEnableVertexAttribArray = nullptr; }
extern "C" { void* __glewFramebufferRenderbuffer = nullptr; }
extern "C" { void* __glewFramebufferTexture2D = nullptr; }
extern "C" { void* __glewGenBuffers = nullptr; }
extern "C" { void* __glewGenFramebuffers = nullptr; }
extern "C" { void* __glewGenRenderbuffers = nullptr; }
extern "C" { void* __glewGenVertexArrays = nullptr; }
extern "C" { void* __glewGetProgramInfoLog = nullptr; }
extern "C" { void* __glewGetProgramiv = nullptr; }
extern "C" { void* __glewGetShaderInfoLog = nullptr; }
extern "C" { void* __glewGetShaderiv = nullptr; }
extern "C" { void* __glewGetUniformLocation = nullptr; }
