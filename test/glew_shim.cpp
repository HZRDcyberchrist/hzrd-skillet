  __glewCompileShader = eglGetProcAddress("glCompileShader");
  __glewCreateProgram = eglGetProcAddress("glCreateProgram");
  __glewCreateShader = eglGetProcAddress("glCreateShader");
  __glewDeleteBuffers = eglGetProcAddress("glDeleteBuffers");
  __glewDeleteFramebuffers = eglGetProcAddress("glDeleteFramebuffers");
  __glewDeleteProgram = eglGetProcAddress("glDeleteProgram");
  __glewDeleteRenderbuffers = eglGetProcAddress("glDeleteRenderbuffers");
  __glewDeleteShader = eglGetProcAddress("glDeleteShader");
  __glewDeleteVertexArrays = eglGetProcAddress("glDeleteVertexArrays");
  __glewEnableVertexAttribArray = eglGetProcAddress("glEnableVertexAttribArray");
  __glewFramebufferRenderbuffer = eglGetProcAddress("glFramebufferRenderbuffer");
  __glewFramebufferTexture2D = eglGetProcAddress("glFramebufferTexture2D");
  __glewGenBuffers = eglGetProcAddress("glGenBuffers");
  __glewGenFramebuffers = eglGetProcAddress("glGenFramebuffers");
  __glewGenRenderbuffers = eglGetProcAddress("glGenRenderbuffers");
  __glewGenVertexArrays = eglGetProcAddress("glGenVertexArrays");
  __glewGetProgramInfoLog = eglGetProcAddress("glGetProgramInfoLog");
  __glewGetProgramiv = eglGetProcAddress("glGetProgramiv");
  __glewGetShaderInfoLog = eglGetProcAddress("glGetShaderInfoLog");
  __glewGetShaderiv = eglGetProcAddress("glGetShaderiv");
  __glewGetUniformLocation = eglGetProcAddress("glGetUniformLocation");
  __glewLinkProgram = eglGetProcAddress("glLinkProgram");
  __glewRenderbufferStorage = eglGetProcAddress("glRenderbufferStorage");
  __glewShaderSource = eglGetProcAddress("glShaderSource");
  __glewTransformFeedbackVaryings = eglGetProcAddress("glTransformFeedbackVaryings");
  __glewUniform1f = eglGetProcAddress("glUniform1f");
  __glewUniform1i = eglGetProcAddress("glUniform1i");
  __glewUniform2f = eglGetProcAddress("glUniform2f");
